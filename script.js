document.getElementById('akan-form').addEventListener('submit', function(e) {
    e.preventDefault();

    // 1. Get values from inputs
    const day = parseInt(document.getElementById('day').value);
    const month = parseInt(document.getElementById('month').value);
    const year = parseInt(document.getElementById('year').value);
    const gender = document.getElementById('Gender').value;

    // 2. Validate Date
    const birthDate = new Date(year, month - 1, day);
    
    if (birthDate.getDate() !== day || birthDate.getMonth() !== month - 1) {
        alert("Please enter a valid date!");
        return;
    }

    // 3. Define Names
    const maleNames = ["Kwasi", "Kwadwo", "Kwabena", "Kwaku", "Yaw", "Kofi", "Kwame"];
    const femaleNames = ["Akosua", "Adwoa", "Abenaa", "Akua", "Yaa", "Afua", "Ama"];

    // 4. Determine Day of Week (0 = Sunday, 6 = Saturday)
    const dayOfWeek = birthDate.getDay();

    // 5. Select Name
    let akanName = (gender === "male") ? maleNames[dayOfWeek] : femaleNames[dayOfWeek];

  
// Display results
const resultDiv = document.getElementById('results-section');
const displayP = document.getElementById('display-name');


const dayNames = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
const dayOfBirth = dayNames[birthDate.getDay()]; 

// Update the text to show both the day and the Akan name
displayP.innerHTML = `You were born on a <strong>${dayOfBirth}</strong>.<br>Your Akan name is <strong>${akanName}</strong>.`;

// Show the hidden div
resultDiv.classList.remove('hidden');
    

    
    
});






















































































































































































































































































































































































































































































































































































































































































































































































































































 




























































































































 















































































































































































































































































































































































































































































































 




























































































































 





























































































































































































































































































































































































































































